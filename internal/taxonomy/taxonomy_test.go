// ptr is a string pointer for the *string API (nil == Python None).
func ptr(s string) *string { return &s }

// useConfig points ConfigDir at the committed config snapshot and restores it
// afterwards (the twin of monkeypatch.setattr(TX, "CONFIG_DIR", ...)).
func useConfig(t *testing.T, dir string) {
	t.Helper()
	oldRoot, oldDir := RepoRoot, ConfigDir
	t.Cleanup(func() { RepoRoot, ConfigDir = oldRoot, oldDir })
	SetConfigDir(dir)
}

// tmpConfig is _tmp_config: a per-test copy of the shipped config dir, so a
// test can add or modify map files without touching the real ones.
func tmpConfig(t *testing.T) string {
	t.Helper()
	dst := filepath.Join(t.TempDir(), "config")
	copyTree(t, filepath.Join("testdata", "config"), dst)
	useConfig(t, filepath.Dir(dst))
	return dst
}

// copyTree copies a small directory tree (config files, test fixtures).
func copyTree(t *testing.T, src, dst string) {
	t.Helper()
	entries, err := os.ReadDir(src)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(dst, 0o755); err != nil {
		t.Fatal(err)
	}
	for _, e := range entries {
		if e.IsDir() {
			copyTree(t, filepath.Join(src, e.Name()), filepath.Join(dst, e.Name()))
			continue
		}
		raw, err := os.ReadFile(filepath.Join(src, e.Name()))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dst, e.Name()), raw, 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// loadVectors decodes a committed vector table (generated by the Python twin).
func loadVectors(t *testing.T, name string, out any) {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("testdata", "vectors", name))
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(raw, out); err != nil {
		t.Fatal(err)
	}
}

// equalStrings is the ordered list comparison.
func equalStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

