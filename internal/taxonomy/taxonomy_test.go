type mapFileVector struct {
	Name      string  `json:"name"`
	Text      *string `json:"text"`
	ErrorKind *string `json:"error_kind"`
	Error     *string `json:"error"`
	MapJSON   *string `json:"map_json"`
}

func TestMapFileVectors(t *testing.T) {
	var vectors []mapFileVector
	loadVectors(t, "taxonomy_errors.json", &vectors)
	if len(vectors) < 20 {
		t.Fatalf("vector table too small: %d", len(vectors))
	}
	ok, failed := 0, 0
	for _, v := range vectors {
		dir := t.TempDir()
		path := filepath.Join(dir, v.Name)
		if v.Text != nil {
			if err := os.WriteFile(path, []byte(*v.Text), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		if v.ErrorKind == nil {
			data, err := readMapFile(path)
			if err != nil {
				t.Errorf("%s: unexpected error %v", v.Name, err)
				continue
			}
			ok++
			if v.MapJSON != nil {
				if got := validation.CanonCompact(mapValue(data)); got != *v.MapJSON {
					t.Errorf("%s: map = %s\n want %s", v.Name, got, *v.MapJSON)
				}
			}
			continue
		}
		// the fail-loud deployment check (a missing file is an error here,
		// where read_map_file treats absence as a miss)
		err := ValidateMapFile(path)
		if err == nil {
			t.Errorf("%s: want %s, got no error", v.Name, *v.Error)
			continue
		}
		failed++
		want := strings.ReplaceAll(*v.Error, "{dir}", dir)
		if *v.ErrorKind == "FileNotFoundError" {
			if !errors.Is(err, fs.ErrNotExist) {
				t.Errorf("%s: error %v is not fs.ErrNotExist", v.Name, err)
			}
			continue
		}
		// The YAML parser's own text is PyYAML's, which yaml.v3 cannot
		// reproduce (reported as a deviation); the prefix is byte-exact.
		if strings.HasSuffix(want, "is not valid YAML: ") ||
			strings.Contains(want, "is not valid YAML:") {
			prefix := want[:strings.Index(want, "is not valid YAML:")+len("is not valid YAML: ")]
			if !strings.HasPrefix(err.Error(), prefix) {
				t.Errorf("%s: error %q lacks the prefix %q", v.Name, err, prefix)
			}
			continue
		}
		if err.Error() != want {
			t.Errorf("%s:\n got %q\nwant %q", v.Name, err.Error(), want)
		}
	}
	if ok < 5 || failed < 10 {
		t.Errorf("vector mix = %d ok / %d failed; want both cases", ok, failed)
	}
}
