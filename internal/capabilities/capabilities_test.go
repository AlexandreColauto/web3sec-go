func TestNormalizeLabelCollapsesEverySpelling(t *testing.T) {
	variants := []string{"Control Perceived Asset Price",
		"control-perceived  asset_price",
		"  control perceived asset price ",
		"control_perceived_asset_price"}
	seen := map[string]struct{}{}
	for _, v := range variants {
		got := NormalizeLabel(v)
		if got != "control_perceived_asset_price" {
			t.Errorf("NormalizeLabel(%q) = %q, want control_perceived_asset_price",
				v, got)
		}
		seen[got] = struct{}{}
	}
	if len(seen) != 1 {
		t.Errorf("normalized variants collapsed to %d keys, want 1", len(seen))
	}
}

func TestKindOfUsesTheTaxonomyAndAdmitsFreeText(t *testing.T) {
	cases := []struct {
		label, want string
	}{
		{"hold_governor", "authority"},
		{"Hold-Governor", "authority"}, // normalized first
		{"move spot price", "market"},
	}
	for _, c := range cases {
		got, ok := KindOf(c.label)
		if !ok || got != c.want {
			t.Errorf("KindOf(%q) = %q, %v; want %q, true", c.label, got, ok, c.want)
		}
	}
	if got, ok := KindOf("whatever the model invented"); ok {
		t.Errorf("free text classified as %q; want unknown", got)
	}
}

func TestCapabilityDeltaSeparatesGainedFromRequired(t *testing.T) {
	f := finding([]string{"move spot price", "extract protocol liquidity"},
		[]string{"Move-  Spot Price"})
	d := CapabilityDelta(f)
	if got := strSlice(objAt(d, "retained")); !equalStrings(got, []string{"move_spot_price"}) {
		t.Errorf("retained = %v, want [move_spot_price]", got)
	}
	if got := strSlice(objAt(d, "gained")); !equalStrings(got, []string{"extract_protocol_liquidity"}) {
		t.Errorf("gained = %v, want [extract_protocol_liquidity]", got)
	}
	if got := strSlice(objAt(d, "required")); !equalStrings(got, []string{"move_spot_price"}) {
		t.Errorf("required = %v, want [move_spot_price]", got)
	}
	kinds := strSlice(objAt(d, "kinds"))
	if !contains(kinds, "market") || !contains(kinds, "asset") {
		t.Errorf("kinds = %v, want market and asset", kinds)
	}
}

func TestRequiredFallsBackToPreconditions(t *testing.T) {
	// Older findings record prose preconditions, not capability lists. The
	// fallback is best-effort and visible as such in `unclassified`.
	f := validation.VObj(kv("preconditions",
		strArr([]string{"attacker must hold pauser role"})))
	if got := Required(f); !equalStrings(got, []string{"attacker_must_hold_pauser_role"}) {
		t.Errorf("required = %v, want [attacker_must_hold_pauser_role]", got)
	}
	if got, ok := KindOf("attacker must hold pauser role"); ok {
		t.Errorf("prose precondition classified as %q; want unknown", got)
	}
}

