// finding builds a minimal finding Value with the given capabilities.
func finding(granted, required []string) validation.Value {
	return validation.VObj(kv("capabilities", validation.VObj(
		kv("granted", strArr(granted)),
		kv("required", strArr(required)),
	)))
}

// strSlice reads a JSON array Value back into []string.
func strSlice(v validation.Value) []string {
	out := make([]string, 0, len(v.A))
	for _, e := range v.A {
		out = append(out, e.S)
	}
	return out
}

// equalStrings is the ordered list comparison.
func equalStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// contains is the membership check.
func contains(items []string, want string) bool {
	for _, it := range items {
		if it == want {
			return true
		}
	}
	return false
}

// loadVectors decodes a committed vector table (generated by the Python twin).
func loadVectors(t *testing.T, name string, out any) {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("testdata", "vectors", name))
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(raw, out); err != nil {
		t.Fatal(err)
	}
}

